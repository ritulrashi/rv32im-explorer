#!/usr/bin/env python3
"""Phase 4 investigations of the negative and surprising results (RESULTS.md).
Every experiment here runs fresh from the built ELFs; the exact command line of
each simulator run is recorded in the output.

    scripts/phase4_investigations.py BUILD_DIR OUT.md

E1  Is tiled GEMM's extra D-miss count on small_caches caused by set conflicts?
    Same capacity, fully associative (dcache.assoc = 64 -> 1 set).
E2  Does padding the rows (stride N+4) remove the conflicts? (C -O3 variants.)
E3  Why is bimodal slower than static not-taken on asm gemm_tiled_unroll4?
E4  Did clang -O3 really generate identical code for gemm naive and unroll4
    at N=32? (diff of the gemm function disassembly)
"""
import json
import os
import re
import subprocess
import sys


def run(build, workload, cfg, sets=()):
    cmd = [os.path.join(build, "rvsim-pipe"), os.path.join(build, "workloads", workload + ".elf"),
           "--config", f"configs/{cfg}.cfg"]
    for s in sets:
        cmd += ["--set", s]
    cmd += ["--stats", "-"]
    out = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if out.returncode != 0:
        raise SystemExit(f"run failed ({out.returncode}): {' '.join(cmd)}\n{out.stderr}")
    roi = json.loads(out.stdout)["roi"]
    shown = " ".join(cmd[:-2])
    return roi, shown


def function_body(dump, name):
    """Instruction text (address-free) of one function in an objdump listing."""
    lines, inside = [], False
    with open(dump, encoding="utf-8") as f:
        for line in f:
            if re.match(rf"^[0-9a-f]+ <{name}>:", line):
                inside = True
                continue
            if inside:
                if not line.strip():
                    break
                m = re.match(r"^\s*[0-9a-f]+:\s+[0-9a-f]+\s+(.*)$", line.rstrip())
                if m:
                    lines.append(re.sub(r"\s+", " ", m.group(1)))
    return lines


def main():
    build, out_path = sys.argv[1], sys.argv[2]
    o = ["# Phase 4 investigations (generated by scripts/phase4_investigations.py; do not edit)", ""]
    commands = []

    # ---- E1 -------------------------------------------------------------------
    o += ["## E1: set conflicts in the 1 KiB 2-way D-cache", "",
          "Same 1 KiB capacity and 16 B lines; `assoc=64` makes it fully associative (1 set), which "
          "removes conflict misses by construction while keeping capacity and compulsory misses.", "",
          "| workload | D-misses 2-way | D-misses fully assoc. | ROI cycles 2-way | ROI cycles fully assoc. |",
          "|---|---:|---:|---:|---:|"]
    for w in ["asm-gemm_naive-n32", "asm-gemm_tiled-n32", "asm-gemm_naive-n64", "asm-gemm_tiled-n64",
              "c-O3-gemm_naive-n64", "c-O3-gemm_tiled-n64"]:
        r2, c2 = run(build, w, "small_caches")
        rf, cf = run(build, w, "small_caches", ["dcache.assoc=64"])
        commands += [c2, cf]
        o.append(f"| `{w}` | {r2['dcache']['misses']:,} | {rf['dcache']['misses']:,} | "
                 f"{r2['cycles']:,} | {rf['cycles']:,} |")
    o.append("")

    # ---- E2 -------------------------------------------------------------------
    o += ["## E2: padding each row by 4 words (C, clang -O3)", "",
          "| workload | config | D-misses | ROI cycles | retired |", "|---|---|---:|---:|---:|"]
    for n in (32, 64):
        for w in [f"c-O3-gemm_naive-n{n}", f"c-O3-gemm_naive_pad-n{n}",
                  f"c-O3-gemm_tiled-n{n}", f"c-O3-gemm_tiled_pad-n{n}"]:
            for cfg in ("small_caches", "big"):
                r, c = run(build, w, cfg)
                commands.append(c)
                o.append(f"| `{w}` | {cfg} | {r['dcache']['misses']:,} | {r['cycles']:,} | {r['retired']:,} |")
    o.append("")

    # ---- E3 -------------------------------------------------------------------
    o += ["## E3: predictors on asm gemm_tiled_unroll4", "",
          "With T = 8 and the k loop unrolled x4, the innermost loop runs exactly 2 iterations per "
          "(i, j, tile): its backward branch goes taken, not-taken, taken, not-taken, ... "
          "That inner branch executes 2 * (N/8)^3 * 8^2 times = 8,192 (N=32) or 65,536 (N=64).", "",
          "| N | config | cond branches | cond mispredicts | branch cycles | ROI cycles |",
          "|---:|---|---:|---:|---:|---:|"]
    for n in (32, 64):
        for cfg in ("baseline", "bimodal_btb", "gshare_btb"):
            r, c = run(build, f"asm-gemm_tiled_unroll4-n{n}", cfg)
            commands.append(c)
            o.append(f"| {n} | {cfg} | {r['branch_events']['cond_branches']:,} | "
                     f"{r['branch_events']['cond_mispredicts']:,} | {r['cpi_stack_cycles']['branch']:,} | "
                     f"{r['cycles']:,} |")
    o.append("")

    # ---- E4 -------------------------------------------------------------------
    o += ["## E4: is clang -O3's code for gemm naive and gemm unroll4 identical?", ""]
    def canon(insn):
        # Sort the two source operands of commutative R-type ops, so that
        # `add s1,s2,s1` and `add s1,s1,s2` compare equal.
        m = re.match(r"^(add|mul|and|or|xor) (\w+),(\w+),(\w+)$", insn)
        if not m:
            return insn
        op, rd, a, b = m.groups()
        return f"{op} {rd},{min(a, b)},{max(a, b)}"

    for n in (32, 64):
        a = function_body(os.path.join(build, "workloads", f"c-O3-gemm_naive-n{n}.elf.dump"), "gemm")
        b = function_body(os.path.join(build, "workloads", f"c-O3-gemm_unroll4-n{n}.elf.dump"), "gemm")
        differing = sum(1 for x, y in zip(a, b) if x != y) + abs(len(a) - len(b))
        same_canon = len(a) == len(b) and all(canon(x) == canon(y) for x, y in zip(a, b))
        o.append(f"- N={n}: `gemm` is {len(a)} instructions (naive) vs {len(b)} (unroll4); "
                 f"identical: **{'yes' if a == b else 'no'}** ({differing} differing lines); "
                 f"identical up to the operand order of commutative ops (add/mul/and/or/xor): "
                 f"**{'yes' if same_canon else 'no'}**")
    o.append("")
    o.append("Command: compare the `<gemm>` function bodies (addresses stripped) of "
             "`build/release/workloads/c-O3-gemm_{naive,unroll4}-n{32,64}.elf.dump`.")
    o.append("")

    o += ["## Simulator command lines used above", "", "```"] + commands + ["```", ""]
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(o))
    print(f"phase4 investigations: {len(commands)} simulator runs -> {out_path}")


if __name__ == "__main__":
    main()
