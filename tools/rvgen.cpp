// rvgen: seeded random RV32IM program generator (contract §9).
//
//   rvgen --seed N [--units N]  > prog.S
//
// Output is GNU assembly linked with tests/riscv-tests-env/link.ld. Using the
// assembler (rather than emitting machine code ourselves) gives an encoder
// that is independent of our decoder, and keeps failing programs readable.
//
// Determinism (rule 5): the same seed produces byte-identical output on every
// platform. This rules out std::mt19937 + std::uniform_int_distribution, whose
// distribution algorithms are implementation-defined (libstdc++ and libc++
// give different values for the same seed). We use splitmix64 to seed
// xoshiro256** and our own unbiased range reduction. No floating point.
//
// Termination is guaranteed by construction:
//   * every branch and jump goes forward, to a label emitted later;
//   * the only backward edges are loops with a fixed trip count on a reserved
//     counter register (x30) that no other instruction writes;
//   * no labels are pending when a loop starts, and branches inside a loop
//     land inside the loop, so control can never enter a loop body except
//     through its counter initialisation.
// Memory accesses are always aligned and inside a 4 KiB data region addressed
// through x31 (also reserved), so no program faults.
#include <cstdint>
#include <cstdio>
#include <string>
#include <vector>

#include "cli_common.h"

namespace {

class Rng {
 public:
  explicit Rng(uint64_t seed) {
    for (auto& w : s_) w = splitmix64(seed);
  }
  uint64_t next() {  // xoshiro256** (Blackman & Vigna)
    const uint64_t result = rotl(s_[1] * 5, 7) * 9;
    const uint64_t t = s_[1] << 17;
    s_[2] ^= s_[0];
    s_[3] ^= s_[1];
    s_[1] ^= s_[2];
    s_[0] ^= s_[3];
    s_[2] ^= t;
    s_[3] = rotl(s_[3], 45);
    return result;
  }
  // Uniform in [0, n), n >= 1, by rejection: discard the top partial block of
  // the 64-bit range so every residue is equally likely.
  uint32_t below(uint32_t n) {
    const uint64_t limit = UINT64_MAX - (UINT64_MAX % n);
    uint64_t x;
    do {
      x = next();
    } while (x >= limit);
    return static_cast<uint32_t>(x % n);
  }
  uint32_t u32() { return static_cast<uint32_t>(next() >> 32); }
  bool permille(uint32_t p) { return below(1000) < p; }

 private:
  static uint64_t rotl(uint64_t x, int k) { return (x << k) | (x >> (64 - k)); }
  static uint64_t splitmix64(uint64_t& x) {
    uint64_t z = (x += 0x9E3779B97F4A7C15ull);
    z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ull;
    z = (z ^ (z >> 27)) * 0x94D049BB133111EBull;
    return z ^ (z >> 31);
  }
  uint64_t s_[4];
};

constexpr unsigned kLoopReg = 30;
constexpr unsigned kBaseReg = 31;

class Gen {
 public:
  Gen(uint64_t seed, unsigned units) : rng_(seed), seed_(seed), units_(units) {
    static const uint32_t kDep[] = {0, 300, 600, 900};
    dep_permille_ = kDep[seed % 4];
  }

  std::string run() {
    line("# Generated by rvgen. Reproduce with: rvgen --seed %llu --units %u",
         static_cast<unsigned long long>(seed_), units_);
    line("# dependency_permille=%u (probability x1000 that a source reuses a recent destination)",
         dep_permille_);
    line("  .section .text.init");
    line("  .globl _start");
    line("_start:");
    line("  la x%u, rvgen_data + 2048", kBaseReg);
    line("  li x%u, 0", kLoopReg);
    for (unsigned r = 1; r < kLoopReg; ++r) line("  li x%u, %d", r, static_cast<int32_t>(interesting()));

    for (unsigned u = 0; u < units_; ++u) unit(/*in_loop=*/false, /*loop_left=*/0);
    place_all_pending();

    line("rvgen_end:");
    line("  li x5, 1");
    line("  la x6, tohost");
    line("  sw x5, 0(x6)");
    line("rvgen_spin:");
    line("  j rvgen_spin");

    line("  .section .data");
    line("  .align 12");
    line("rvgen_data:");
    for (int k = 0; k < 1024; ++k) line("  .word 0x%08x", rng_.u32());
    line("  .section .tohost, \"aw\", @progbits");
    line("  .align 6");
    line("  .globl tohost");
    line("tohost: .dword 0");
    line("  .align 6");
    line("  .globl fromhost");
    line("fromhost: .dword 0");
    return out_;
  }

 private:
  struct Pending {
    unsigned label;
    unsigned remaining;  // units still to be emitted before the label
  };

  void line(const char* text) {
    out_ += text;
    out_ += '\n';
  }
  template <typename A0, typename... A>
  void line(const char* fmt, A0 a0, A... args) {
    char b[160];
    std::snprintf(b, sizeof b, fmt, a0, args...);
    out_ += b;
    out_ += '\n';
  }

  // Register values that stress corner cases more often than uniform random.
  uint32_t interesting() {
    static const uint32_t kSpecial[] = {0, 1, 0xFFFFFFFF, 0x80000000, 0x7FFFFFFF, 0x80000001, 2, 31, 32};
    if (rng_.below(3) == 0) return kSpecial[rng_.below(sizeof kSpecial / sizeof kSpecial[0])];
    return rng_.u32();
  }
  unsigned dst() {  // x0..x29: never the reserved x30/x31
    const unsigned r = rng_.below(kLoopReg);
    recent_[recent_n_++ % 4] = r;
    return r;
  }
  unsigned src() {
    if (recent_n_ > 0 && rng_.permille(dep_permille_)) {
      return recent_[rng_.below(recent_n_ < 4 ? recent_n_ : 4)];
    }
    return rng_.below(32);
  }
  int32_t imm12() { return static_cast<int32_t>(rng_.below(4096)) - 2048; }

  // Registers a forward label to be placed after `skip` further units. The
  // +1 accounts for the after_unit() call that ends the current unit.
  void new_label(unsigned skip) { pending_.push_back({next_label_++, skip + 1}); }
  void place_all_pending() {
    for (const auto& p : pending_) line("L%u:", p.label);
    pending_.clear();
  }
  void after_unit() {
    for (auto& p : pending_) {
      if (p.remaining > 0) --p.remaining;
    }
    for (size_t k = 0; k < pending_.size();) {
      if (pending_[k].remaining == 0) {
        line("L%u:", pending_[k].label);
        pending_.erase(pending_.begin() + static_cast<long>(k));
      } else {
        ++k;
      }
    }
  }

  // One "unit": an instruction or a short fixed sequence. Forward branch
  // distances are counted in units.
  void unit(bool in_loop, unsigned loop_left) {
    // Forward skip distance; inside a loop the label must land in the body.
    auto skip = [&]() {
      unsigned k = rng_.below(5);
      if (in_loop && k > loop_left) k = loop_left;
      return k;
    };
    static const char* kR[] = {"add", "sub", "sll", "slt", "sltu", "xor", "srl", "sra", "or", "and"};
    static const char* kI[] = {"addi", "slti", "sltiu", "xori", "ori", "andi"};
    static const char* kSh[] = {"slli", "srli", "srai"};
    static const char* kM[] = {"mul", "mulh", "mulhsu", "mulhu", "div", "divu", "rem", "remu"};
    static const char* kB[] = {"beq", "bne", "blt", "bge", "bltu", "bgeu"};
    struct Ld { const char* op; unsigned size; };
    static const Ld kLd[] = {{"lb", 1}, {"lbu", 1}, {"lh", 2}, {"lhu", 2}, {"lw", 4}};
    static const Ld kSt[] = {{"sb", 1}, {"sh", 2}, {"sw", 4}};
    auto offset = [&](unsigned size) {
      return static_cast<int32_t>(rng_.below(4096 / size) * size) - 2048;
    };

    unsigned pick = rng_.below(100);
    // Loops: only outside loops and with no forward labels pending (§ header).
    if (pick >= 97 && (in_loop || !pending_.empty())) pick = 0;

    // IMPORTANT: every random draw is its own statement. C++ leaves the
    // evaluation order of function arguments unspecified, so writing
    // line(fmt, rng(), dst(), ...) could consume random numbers in a
    // different order on another compiler, and break rule 5.
    if (pick < 18) {
      const unsigned a = src();
      const unsigned b = src();
      const char* op = kR[rng_.below(10)];
      const unsigned d = dst();
      line("  %s x%u, x%u, x%u", op, d, a, b);
    } else if (pick < 30) {
      const unsigned a = src();
      const char* op = kI[rng_.below(6)];
      const unsigned d = dst();
      const int32_t imm = imm12();
      line("  %s x%u, x%u, %d", op, d, a, imm);
    } else if (pick < 36) {
      const unsigned a = src();
      const char* op = kSh[rng_.below(3)];
      const unsigned d = dst();
      const unsigned sh = rng_.below(32);
      line("  %s x%u, x%u, %u", op, d, a, sh);
    } else if (pick < 40) {
      const char* op = rng_.below(2) ? "lui" : "auipc";
      const unsigned d = dst();
      const unsigned imm = rng_.below(1u << 20);
      line("  %s x%u, 0x%x", op, d, imm);
    } else if (pick < 50) {
      const unsigned a = src();
      const unsigned b = src();
      const char* op = kM[rng_.below(8)];
      const unsigned d = dst();
      line("  %s x%u, x%u, x%u", op, d, a, b);
    } else if (pick < 64) {
      const auto& l = kLd[rng_.below(5)];
      const unsigned d = dst();
      const int32_t off = offset(l.size);
      line("  %s x%u, %d(x%u)", l.op, d, off, kBaseReg);
    } else if (pick < 74) {
      const auto& s = kSt[rng_.below(3)];
      const unsigned v = src();
      const int32_t off = offset(s.size);
      line("  %s x%u, %d(x%u)", s.op, v, off, kBaseReg);
    } else if (pick < 84) {
      const unsigned a = src();
      const unsigned b = src();
      const char* op = kB[rng_.below(6)];
      const unsigned k = skip();
      line("  %s x%u, x%u, L%u", op, a, b, next_label_);
      new_label(k);
    } else if (pick < 88) {
      const unsigned d = dst();
      const unsigned k = skip();
      line("  jal x%u, L%u", d, next_label_);
      new_label(k);
    } else if (pick < 91) {
      // Forward indirect jump; offset 1 exercises JALR clearing bit 0.
      const unsigned tmp = 1 + rng_.below(kLoopReg - 1);
      const unsigned d = dst();
      const unsigned off = rng_.below(2);
      const unsigned k = skip();
      line("  la x%u, L%u", tmp, next_label_);
      line("  jalr x%u, %u(x%u)", d, off, tmp);
      new_label(k);
    } else if (pick < 92) {
      line("  %s", rng_.below(2) ? "fence" : "fence.i");
    } else if (pick < 97) {
      const unsigned d = dst();
      const uint32_t v = interesting();
      line("  li x%u, %d", d, static_cast<int32_t>(v));
    } else {
      const unsigned trips = 1 + rng_.below(6);
      const unsigned body = 3 + rng_.below(10);
      const unsigned top = next_label_++;
      line("  li x%u, %u", kLoopReg, trips);
      line("L%u:", top);
      for (unsigned b = 0; b < body; ++b) unit(/*in_loop=*/true, body - b - 1);
      line("  addi x%u, x%u, -1", kLoopReg, kLoopReg);
      line("  bnez x%u, L%u", kLoopReg, top);
    }
    after_unit();
  }

  Rng rng_;
  uint64_t seed_;
  unsigned units_;
  uint32_t dep_permille_ = 0;
  std::string out_;
  std::vector<Pending> pending_;
  unsigned next_label_ = 1;
  unsigned recent_[4] = {};
  unsigned recent_n_ = 0;
};

}  // namespace

int main(int argc, char** argv) {
  uint64_t seed = 0;
  bool have_seed = false;
  unsigned units = 0;
  try {
    for (int k = 1; k < argc; ++k) {
      const std::string a = argv[k];
      if (a == "--seed") {
        seed = rvx::cli::next_num(k, argc, argv);
        have_seed = true;
      } else if (a == "--units") {
        units = static_cast<unsigned>(rvx::cli::next_num(k, argc, argv));
      } else {
        throw std::runtime_error("unknown argument " + a);
      }
    }
    if (!have_seed) throw std::runtime_error("--seed is required");
  } catch (const std::exception& e) {
    std::fprintf(stderr, "rvgen: %s\nusage: rvgen --seed N [--units N]\n", e.what());
    return 2;
  }
  if (units == 0) {
    // Program size is itself derived from the seed (50..400 units).
    Rng sizer(seed ^ 0x5EEDull);
    units = 50 + sizer.below(351);
  }
  std::fputs(Gen(seed, units).run().c_str(), stdout);
  return 0;
}
