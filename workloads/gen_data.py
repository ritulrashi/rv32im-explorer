#!/usr/bin/env python3
"""Generates input data and independently computed expected results for the
Phase 4 workloads, as a GNU assembler data file.

    gen_data.py --kernel dot  --n 1024 --seed 1 --out data.S
    gen_data.py --kernel gemm --n 32   --seed 1 --out data.S
    gen_data.py --selftest

Determinism (rule 5): values come from splitmix64, implemented here, not from
Python's `random` module (whose algorithms are only guaranteed stable within a
Python version). Values are in 0..255 so no int32 product or sum overflows
(dot: <= 1024 * 255^2 < 2^31; gemm-64: <= 64 * 255^2), which keeps the C
kernels free of signed-overflow undefined behaviour.

Every array is aligned to 4 KiB (.align 12). That alignment is deliberate and
discussed in RESULTS.md (cache set conflicts).
"""
import argparse
import sys

MASK32 = 0xFFFFFFFF
MASK64 = 0xFFFFFFFFFFFFFFFF


def splitmix64(state):
    """Yields an endless stream of 64-bit values from a 64-bit seed."""
    while True:
        state = (state + 0x9E3779B97F4A7C15) & MASK64
        z = state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK64
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK64
        yield z ^ (z >> 31)


def values(seed, count):
    gen = splitmix64(seed)
    return [next(gen) & 0xFF for _ in range(count)]


def checksum(words):
    """h = h * 31 + x (mod 2^32), in order. Same as check.S and roi.h."""
    h = 0
    for x in words:
        h = (h * 31 + (x & MASK32)) & MASK32
    return h


def matmul(a, b, n):
    c = [0] * (n * n)
    for i in range(n):
        for j in range(n):
            c[i * n + j] = sum(a[i * n + k] * b[k * n + j] for k in range(n)) & MASK32
    return c


def emit_array(out, name, words):
    out.append("  .align 12")
    out.append(f"  .globl {name}")
    out.append(f"{name}:")
    for k in range(0, len(words), 8):
        out.append("  .word " + ", ".join(str(w) for w in words[k:k + 8]))


def padded(words, n, pad):
    """Row-major n x n matrix stored with a row stride of n + pad words; the
    pad columns are zero and never read by the kernels."""
    if pad == 0:
        return words
    out = []
    for i in range(n):
        out += words[i * n:(i + 1) * n] + [0] * pad
    return out


def generate(kernel, n, seed, pad=0):
    out = [f"# Generated by workloads/gen_data.py --kernel {kernel} --n {n} --seed {seed} --pad {pad}",
           "  .section .data"]
    if kernel == "dot":
        a, b = values(seed, n), values(seed + 1, n)
        emit_array(out, "vec_a", a)
        emit_array(out, "vec_b", b)
        expected = sum(x * y for x, y in zip(a, b)) & MASK32
        out += ["  .align 6", "  .globl dot_expected", f"dot_expected: .word {expected}"]
    elif kernel == "gemm":
        # The logical matrices (and so the expected result) do not depend on
        # the padding; only the storage layout does.
        a, b = values(seed, n * n), values(seed + 1, n * n)
        emit_array(out, "mat_a", padded(a, n, pad))
        emit_array(out, "mat_b", padded(b, n, pad))
        emit_array(out, "mat_c", [0] * (n * (n + pad)))
        expected = checksum(matmul(a, b, n))  # over the n*n logical elements, row-major
        out += ["  .align 6", "  .globl gemm_expected", f"gemm_expected: .word {expected}"]
    else:
        raise ValueError(f"unknown kernel {kernel}")
    return "\n".join(out) + "\n"


def selftest():
    """Hand-computed cases for the reference arithmetic."""
    # ((1 * 31) + 2) * 31 + 3 = 961 + 62 + 3 = 1026
    assert checksum([1, 2, 3]) == 1026
    # [[1,2],[3,4]] x [[5,6],[7,8]] = [[1*5+2*7, 1*6+2*8], [3*5+4*7, 3*6+4*8]] = [[19,22],[43,50]]
    assert matmul([1, 2, 3, 4], [5, 6, 7, 8], 2) == [19, 22, 43, 50]
    # wrap-around is mod 2^32
    assert checksum([MASK32, 1]) == (MASK32 * 31 + 1) & MASK32
    # splitmix64 reference value for seed 0 (first output of the published algorithm)
    assert next(splitmix64(0)) == 0xE220A8397B1DCDAF
    # same seed, same data
    assert values(7, 16) == values(7, 16)
    # padding inserts zero columns after each row
    assert padded([1, 2, 3, 4], 2, 1) == [1, 2, 0, 3, 4, 0]
    print("gen_data selftest: ok")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--kernel", choices=["dot", "gemm"])
    p.add_argument("--n", type=int)
    p.add_argument("--seed", type=int, default=1)
    p.add_argument("--pad", type=int, default=0, help="gemm only: extra words per matrix row")
    p.add_argument("--out")
    p.add_argument("--selftest", action="store_true")
    args = p.parse_args()
    if args.selftest:
        selftest()
        return 0
    text = generate(args.kernel, args.n, args.seed, args.pad)
    with open(args.out, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
